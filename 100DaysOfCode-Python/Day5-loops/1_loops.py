# Loops

# Things that happen over and over again in our code are called loops. Loops are used to repeat a block of code until a certain condition is met.

# For loop
# A for loop is used to iterate over a sequence (like a list, tuple, string, etc.) and execute a block of code for each item in the sequence.
fruits = ["apple", "banana", "orange"]
for fruit in fruits:
    print(fruit)
    print(fruit + " pie")