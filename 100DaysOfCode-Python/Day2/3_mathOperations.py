# We have certain built-in functions in python which we can use to perform certain operations on data. These functions are called math operations.
# These are:
# Addition
print(2 + 3) # will print 5

# Subtraction
print(5 - 2) # will print 3

# Multiplication
print(2 * 3) # will print 6

# Division
print(6 / 2) # will print 3.0
# This will always return a float value even if the result is a whole number.

# Floor Division
print(6 // 2) # will print 3
# This will return the quotient without the decimal part.

# Modulo
print(7 % 3) # will print 1
# This will return the remainder of the division.

# Exponentiation
print(2 ** 3) # will print 8
# This will return the result of 2 raised to the power of 3.

# Order of operations
# PEMDAS-LR
# Parentheses
# Exponents
# Multiplication and Division (from left to right)
# Addition and Subtraction (from left to right)